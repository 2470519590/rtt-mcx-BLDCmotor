"""Export a numpy MLP archive as app/nn_model.h for the MCU build."""
import argparse
from pathlib import Path
import numpy as np


def c_float(value):
    value = float(value)
    if not np.isfinite(value):
        raise ValueError("model contains a nonfinite coefficient")
    text = f"{value:.9g}"
    if "." not in text and "e" not in text:
        text += ".0"
    return text + "f"


def array_1d(values):
    return ", ".join(c_float(v) for v in np.asarray(values).ravel())


def array_2d(values):
    return "\n".join("    {" + array_1d(row) + "}," for row in np.asarray(values))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("model")
    parser.add_argument("--output", default="app/nn_model.h")
    args = parser.parse_args()
    model = np.load(args.model)
    if "schema" in model and str(model["schema"]) != "residual_v1":
        raise ValueError("candidate feature schema is incompatible with deployed firmware v1")
    w1 = model["hidden_weights"]
    b1 = model["hidden_bias"]
    w2 = model["output_weights"]
    if (w1.ndim != 2 or w1.shape[1] != 6 or b1.shape != (w1.shape[0],)
            or w2.shape != b1.shape or model["input_mean"].shape != (6,)
            or model["input_std"].shape != (6,)
            or np.any(model["input_std"] <= 0)
            or model["output_limit"].shape != () or float(model["output_limit"]) <= 0
            or model["output_bias"].shape != ()):
        raise ValueError("invalid model dimensions, standard deviations or output limit")
    text = f'''#ifndef NN_MODEL_H
#define NN_MODEL_H

/* Generated by tools/export_nn_weights.py; do not edit by hand. */
#define NN_MODEL_INPUTS {w1.shape[1]}U
#define NN_MODEL_HIDDEN {w1.shape[0]}U
static const float nn_model_input_mean[NN_MODEL_INPUTS] = {{{array_1d(model["input_mean"])}}};
static const float nn_model_input_std[NN_MODEL_INPUTS] = {{{array_1d(model["input_std"])}}};
static const float nn_model_hidden_weights[NN_MODEL_HIDDEN][NN_MODEL_INPUTS] = {{
{array_2d(w1)}
}};
static const float nn_model_hidden_bias[NN_MODEL_HIDDEN] = {{{array_1d(b1)}}};
static const float nn_model_output_weights[NN_MODEL_HIDDEN] = {{{array_1d(w2)}}};
static const float nn_model_output_bias = {c_float(model["output_bias"])};
static const float nn_model_output_limit = {c_float(model["output_limit"])};
#endif
'''
    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(text, encoding="utf-8")
    print(f"Exported {output.resolve()}")


if __name__ == "__main__":
    main()
